// Headless Chrome check: page loads, model downloads and runs in the worker, events get Fish LM replies.
import puppeteer from "../jsdeps/node_modules/puppeteer-core/lib/puppeteer/puppeteer-core.js";
const url = process.argv[2] || "http://127.0.0.1:8765/";
const out = process.argv[3] || "shot";
const browser = await puppeteer.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const page = await browser.newPage();
await page.setViewport({ width: 1280, height: 900 });
const errors = [];
page.on("console", (m) => { if (m.type() === "error" || m.type() === "warning") errors.push(`${m.type()}: ${m.text()}`); });
page.on("pageerror", (e) => errors.push("pageerror: " + e.message));
const t0 = Date.now();
await page.goto(url, { waitUntil: "load" });
console.log("isolated:", await page.evaluate(() => crossOriginIsolated));
await page.waitForFunction(() => document.getElementById("status-title").textContent.includes("running") || document.getElementById("status-title").textContent.includes("could not"), { timeout: 180000 });
console.log("status:", await page.$eval("#status-title", (e) => e.textContent), "|", await page.$eval("#status-num", (e) => e.textContent), "|", await page.$eval("#status-note", (e) => e.textContent), `(${Date.now() - t0} ms)`);
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
await page.click("#btn-tap"); await wait(2500);
await page.click("#btn-feed"); await wait(3000);
await page.type("#talk-input", "what is your name"); await page.keyboard.press("Enter"); await wait(3000);
await page.click("#btn-lights"); await wait(3000);
await page.screenshot({ path: `${out}-desktop.png` });
const entries = await page.$$eval("#log .entry", (els) => els.map((e) => e.innerText.replace(/\n+/g, " | ")));
console.log(entries.reverse().join("\n"));
await page.setViewport({ width: 390, height: 844, isMobile: true });
await wait(800);
await page.screenshot({ path: `${out}-phone.png`, fullPage: true });
console.log("horizontal overflow:", await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth));
console.log("errors:", errors.length ? errors.join("\n") : "none");
await browser.close();
